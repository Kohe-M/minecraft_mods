package com.omuraisu.minimap.test;

import static com.omuraisu.minimap.test.MapTests.*;

import java.util.Arrays;

import com.omuraisu.minimap.TerrainRegions;
import com.omuraisu.minimap.TerrainServer;
import com.omuraisu.minimap.client.MinimapClient;
import com.omuraisu.testkit.Scenario;
import com.omuraisu.testkit.Screenshots;

import net.fabricmc.fabric.api.client.gametest.v1.context.ClientGameTestContext;
import net.fabricmc.fabric.api.client.gametest.v1.context.TestSingleplayerContext;
import net.fabricmc.fabric.api.client.gametest.v1.world.TestWorldSave;
import net.minecraft.world.level.ChunkPos;

// 遠くの地形の負荷: 4K で一番引いた地図で、サーバーが遅れず、ワールドに読み込まず、下書きで画面が埋まる
public class TerrainLoadTest implements Scenario {
	@Override
	public String name() {
		return "load";
	}

	@Override
	public void run(ClientGameTestContext context) {
		watchFullLoads();
		resetConfig(context);
		testFarTerrainLoad(context);
	}

	// 4K で一番引いても、サーバーが遅れず、地図のためにチャンクをワールドへ読み込まない。
	// 以前は描画距離の外を 1 つずつ FULL まで読み込み、ヒープを使い切ってサーバーが落ちていた。
	// まだ生成していない場所は、生成を待たずに下書きで埋まる
	private static void testFarTerrainLoad(ClientGameTestContext context) {
		TestWorldSave save;
		int generated;
		try (TestSingleplayerContext singleplayer = context.worldBuilder()
				.setUseConsistentSettings(false)
				.adjustSettings(creator -> creator.setSeed("far terrain load"))
				.create()) {
			save = singleplayer.getWorldSave();
			singleplayer.getConnection().waitForChunksRender();
			openFarMap(context);
			// 画面に入るリージョンの下書きが 3 秒以内にすべて届き、画面が埋まる（生成だけでは 30 秒で画面の 3 割ほど）
			ChunkPos player = context.computeOnClient(client -> client.player.chunkPosition());
			int[] regions = {TerrainRegions.coordinate(player.x() - 120), TerrainRegions.coordinate(player.z() - 67),
					TerrainRegions.coordinate(player.x() + 120), TerrainRegions.coordinate(player.z() + 67)};
			int expected = (regions[2] - regions[0] + 1) * (regions[3] - regions[1] + 1);
			int ticks = 0;
			while (previewed(context, regions) < expected) {
				if (ticks++ >= 60) {
					throw new AssertionError("previews of the ungenerated terrain should arrive within 3 seconds but only "
							+ previewed(context, regions) + " of " + expected + " regions did");
				}
				context.waitTick();
			}
			int early = context.computeOnClient(client -> MinimapClient.FAR_TERRAIN.count(OVERWORLD));
			System.out.printf("far-terrain-preview: %d regions within %d ticks, %d chunks generated by then%n", expected, ticks, early);
			context.waitTicks(30);
			int empty = Screenshots.read(context.takeScreenshot("far-terrain-preview"), image -> {
				int count = 0;
				for (int y = 0; y < image.getHeight(); y++) {
					for (int x = 0; x < image.getWidth(); x++) {
						if (image.getPixel(x, y) == EMPTY_COLOR) {
							count++;
						}
					}
				}
				return count;
			});
			if (empty != 0) {
				throw new AssertionError("previews should fill the map but " + empty + " pixels were empty");
			}

			watchServer(context, singleplayer, "far-terrain-load", 600);
			generated = context.computeOnClient(client -> MinimapClient.FAR_TERRAIN.count(OVERWORLD));
			toggleMap(context);
			if (generated < 1000) {
				throw new AssertionError("far terrain should keep generating but only " + generated + " chunks arrived");
			}
		}
		// 開き直すと、前に届いた色をクライアントのファイルからすぐ出す。メモリにあったチャンクの色は版が残らないので、
		// サーバーがセーブから読み直す。マップ距離の分は開く前から読み直し始めるので、入ったときから数える
		int before = context.computeOnClient(client -> MinimapClient.FAR_TERRAIN.received());
		try (TestSingleplayerContext singleplayer = save.open()) {
			singleplayer.getConnection().waitForChunksRender();
			openFarMap(context);
			context.waitTicks(10);
			int shown = context.computeOnClient(client -> MinimapClient.FAR_TERRAIN.count(OVERWORLD));
			if (shown < generated) {
				throw new AssertionError("far terrain saved on the client should be shown right after opening: " + shown + " / " + generated);
			}
			watchServer(context, singleplayer, "far-terrain-load-reopened", 200);
			int refreshed = context.computeOnClient(client -> MinimapClient.FAR_TERRAIN.received()) - before;
			int[] reads = singleplayer.getServer().computeOnServer(server -> TerrainServer.readCounts());
			System.out.printf("far-terrain-load-reopened: shown %d, refreshed %d, read %d (vanilla %d)%n", shown, refreshed, reads[0], reads[1]);
			// リージョンファイルを自前で読めている（vanilla の IO スレッドに頼っていない）
			if (reads[0] < 100 || reads[1] * 10 > reads[0]) {
				throw new AssertionError("most chunks should be read from the region files directly but " + reads[1] + " / " + reads[0] + " fell back");
			}
			toggleMap(context);
		}
		context.getInput().resizeWindow(854, 480);
		context.waitTicks(3);
	}

	// 下書きが届いたリージョンの数
	private static int previewed(ClientGameTestContext context, int[] regions) {
		return context.computeOnClient(client -> {
			int count = 0;
			for (int z = regions[1]; z <= regions[3]; z++) {
				for (int x = regions[0]; x <= regions[2]; x++) {
					if (MinimapClient.FAR_TERRAIN.preview(OVERWORLD, x * TerrainRegions.BLOCKS, z * TerrainRegions.BLOCKS) != 0) {
						count++;
					}
				}
			}
			return count;
		});
	}

	private static void openFarMap(ClientGameTestContext context) {
		context.getInput().resizeWindow(3840, 2160);
		context.waitTicks(3);
		toggleMap(context);
		context.getInput().setCursorPos(1920, 1080);
		scroll(context, -6);
		assertScale(context, 1);
	}

	// ticks の間、サーバーが遅れず、地図のためにチャンクをワールドへ読み込んでいないことを確かめる
	private static void watchServer(ClientGameTestContext context, TestSingleplayerContext singleplayer, String name, int ticks) {
		singleplayer.getServer().runOnServer(server -> FULL_LOADS.clear());
		long maxTick = 0;
		for (int waited = 0; waited < ticks; waited += 100) {
			context.waitTicks(Math.min(100, ticks - waited));
			maxTick = Math.max(maxTick, singleplayer.getServer().computeOnServer(server -> Arrays.stream(server.getTickTimesNanos()).max().orElse(0)));
		}
		context.takeScreenshot(name);
		long averageTick = singleplayer.getServer().computeOnServer(server -> server.getAverageTickTimeNanos());
		int loads = singleplayer.getServer().computeOnServer(server -> FULL_LOADS.size());
		int chunks = context.computeOnClient(client -> MinimapClient.FAR_TERRAIN.count(OVERWORLD));
		System.out.printf("%s: %d chunks, max tick %d ms, average tick %d ms, loaded into the world %d%n",
				name, chunks, maxTick / 1_000_000, averageTick / 1_000_000, loads);
		if (loads > 100) {
			throw new AssertionError(name + ": " + loads + " chunks were loaded into the world for the map");
		}
		if (maxTick > 1_000_000_000L || averageTick > 50_000_000L) {
			throw new AssertionError(name + ": server fell behind (max tick " + maxTick / 1_000_000 + " ms, average " + averageTick / 1_000_000 + " ms)");
		}
	}
}
